BEGIN;

CREATE TABLE IF NOT EXISTS public.whatsapp_webhook_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key text NOT NULL UNIQUE,
  event_type text NOT NULL,
  message_id text,
  sender_number text,
  whatsapp_number text,
  phone_number_id text,
  message_type text,
  content jsonb,
  meta_timestamp timestamptz,
  message_state text,
  payload jsonb NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS whatsapp_webhook_events_conversation_idx
  ON public.whatsapp_webhook_events (sender_number, meta_timestamp DESC);

CREATE INDEX IF NOT EXISTS whatsapp_webhook_events_message_idx
  ON public.whatsapp_webhook_events (message_id, meta_timestamp DESC);

ALTER TABLE public.whatsapp_webhook_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.whatsapp_webhook_events FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.whatsapp_webhook_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.whatsapp_webhook_events_id_seq TO service_role;

COMMIT;
