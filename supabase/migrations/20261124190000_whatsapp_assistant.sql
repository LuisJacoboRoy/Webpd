BEGIN;

CREATE TABLE IF NOT EXISTS public.whatsapp_conversations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  whatsapp_number text NOT NULL UNIQUE,
  display_name text,
  automated_status text NOT NULL DEFAULT 'automated'
    CHECK (automated_status IN ('automated', 'human')),
  human_paused_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.whatsapp_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id bigint NOT NULL REFERENCES public.whatsapp_conversations(id) ON DELETE CASCADE,
  meta_message_id text,
  direction text NOT NULL CHECK (direction IN ('inbound', 'outbound')),
  role text NOT NULL CHECK (role IN ('user', 'assistant')),
  content text NOT NULL,
  message_type text NOT NULL DEFAULT 'text',
  delivery_state text,
  meta_timestamp timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT whatsapp_messages_meta_id_unique UNIQUE (meta_message_id)
);

CREATE INDEX IF NOT EXISTS whatsapp_messages_conversation_created_idx
  ON public.whatsapp_messages (conversation_id, created_at DESC);

ALTER TABLE public.whatsapp_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_messages ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.whatsapp_conversations FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.whatsapp_messages FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.whatsapp_conversations TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.whatsapp_messages TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.whatsapp_conversations_id_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.whatsapp_messages_id_seq TO service_role;

COMMIT;
